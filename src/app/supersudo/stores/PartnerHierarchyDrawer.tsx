'use client';

import { Button } from '@shop/ui';
import { useTranslation } from '../../../lib/i18n-client';
import { writeInContentLocale } from '@/lib/i18n/locale-script';
import { applyLocalizedTextChange, filledLocalizedTexts, type LocalizedText } from '@/lib/i18n/localized-text';
import type { LanguageCode } from '@/lib/language';
import { AdminSideDrawer } from '../components/AdminSideDrawer';
import { ContentLanguageFields } from '../components/ContentLanguageFields';

export type PartnerHierarchyDraft = {
  kind: 'region' | 'area';
  id: string | null;
  regionId: string;
  texts: LocalizedText[];
  slug: string;
};

interface PartnerHierarchyDrawerProps {
  draft: PartnerHierarchyDraft | null;
  saving: boolean;
  onClose: () => void;
  onChange: (draft: PartnerHierarchyDraft) => void;
  onSave: () => void;
}

export function PartnerHierarchyDrawer({
  draft,
  saving,
  onClose,
  onChange,
  onSave,
}: PartnerHierarchyDrawerProps) {
  const { t } = useTranslation();
  if (!draft) {
    return null;
  }

  const titleKey = draft.kind === 'region'
    ? (draft.id ? 'admin.partnerStores.editRegion' : 'admin.partnerStores.addRegion')
    : (draft.id ? 'admin.partnerStores.editArea' : 'admin.partnerStores.addArea');
  const canSave = filledLocalizedTexts(draft.texts).length > 0;

  const update = (locale: LanguageCode, patch: { text?: string; slug?: string }) => {
    const written = patch.text === undefined
      ? patch
      : { ...patch, text: writeInContentLocale(patch.text, locale) };
    const next = applyLocalizedTextChange({ texts: draft.texts, slug: draft.slug }, locale, written);
    onChange({ ...draft, texts: next.texts, slug: next.slug });
  };

  return (
    <AdminSideDrawer
      open
      onClose={onClose}
      side="right"
      size="panel"
      title={t(titleKey)}
      footer={
        <div className="flex justify-end gap-2">
          <Button type="button" variant="outline" onClick={onClose} disabled={saving}>
            {t('admin.partnerStores.cancel')}
          </Button>
          <Button type="button" variant="primary" onClick={onSave} disabled={saving || !canSave}>
            {saving ? t('admin.partnerStores.saving') : t('admin.partnerStores.save')}
          </Button>
        </div>
      }
    >
      <ContentLanguageFields
        syncKey={draft.id ?? `new-${draft.kind}`}
        textLabel={t('admin.partnerStores.name')}
        slugLabel={t('admin.categories.slug')}
        slugHint={t('admin.categories.slugAutoGenerated')}
        texts={draft.texts}
        slug={draft.slug}
        onChange={update}
      />
    </AdminSideDrawer>
  );
}
