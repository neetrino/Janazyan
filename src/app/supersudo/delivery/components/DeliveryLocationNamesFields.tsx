'use client';

import { writeInContentLocale } from '@/lib/i18n/locale-script';
import { applyLocalizedTextChange } from '@/lib/i18n/localized-text';
import type { LanguageCode } from '@/lib/language';
import { useTranslation } from '@/lib/i18n-client';
import { ContentLanguageFields } from '../../components/ContentLanguageFields';
import type { DeliveryLocationFormData } from '../delivery-location.utils';

type DeliveryLocationNamesFieldsProps = {
  formData: DeliveryLocationFormData;
  syncKey: string;
  onChange: (data: DeliveryLocationFormData) => void;
};

export function DeliveryLocationNamesFields({
  formData,
  syncKey,
  onChange,
}: DeliveryLocationNamesFieldsProps) {
  const { t } = useTranslation();

  const updateCountry = (locale: LanguageCode, patch: { text?: string; slug?: string }) => {
    const written = patch.text === undefined
      ? patch
      : { ...patch, text: writeInContentLocale(patch.text, locale) };
    const next = applyLocalizedTextChange({ texts: formData.countryNames, slug: '' }, locale, written);
    onChange({ ...formData, countryNames: next.texts });
  };

  const updateCity = (locale: LanguageCode, patch: { text?: string; slug?: string }) => {
    const written = patch.text === undefined
      ? patch
      : { ...patch, text: writeInContentLocale(patch.text, locale) };
    const next = applyLocalizedTextChange(
      { texts: formData.cityNames, slug: formData.citySlug },
      locale,
      written,
    );
    onChange({ ...formData, cityNames: next.texts, citySlug: next.slug });
  };

  return (
    <div className="space-y-6">
      <ContentLanguageFields
        syncKey={`${syncKey}-country`}
        textLabel={t('admin.delivery.country')}
        slugLabel={t('admin.categories.slug')}
        slugHint={t('admin.categories.slugAutoGenerated')}
        texts={formData.countryNames}
        slug=""
        showSlug={false}
        onChange={updateCountry}
      />
      <ContentLanguageFields
        syncKey={`${syncKey}-city`}
        textLabel={t('admin.delivery.city')}
        slugLabel={t('admin.categories.slug')}
        slugHint={t('admin.categories.slugAutoGenerated')}
        texts={formData.cityNames}
        slug={formData.citySlug}
        onChange={updateCity}
      />
    </div>
  );
}
